<script lang="ts">
	import PageHeader from '$lib/components/PageHeader.svelte';
	import Icon from '$lib/components/Icon.svelte';
	import MetricCard from '$lib/components/MetricCard.svelte';
	import { app, notify } from '$lib/store.svelte';
	import { compact } from '$lib/engine';

	const series = $derived(app.analytics.series);
	const visible = $derived(series.slice(-12));
	const w = 760;
	const h = 240;
	const maxImp = $derived(Math.max(...visible.map((p) => p.impressions)) * 1.1);
	const maxEng = $derived(Math.max(...visible.map((p) => p.engagement)) * 1.1);
	const impLine = $derived(visible.map((p, i) => `${i === 0 ? 'M' : 'L'}${((i / (visible.length - 1)) * w).toFixed(1)},${(h - 28 - (p.impressions / maxImp) * (h - 56)).toFixed(1)}`).join(' '));
	const engLine = $derived(visible.map((p, i) => `${i === 0 ? 'M' : 'L'}${((i / (visible.length - 1)) * w).toFixed(1)},${(h - 28 - (p.engagement / maxEng) * (h - 56)).toFixed(1)}`).join(' '));
	const impArea = $derived(`${impLine} L${w},${h} L0,${h} Z`);

	const funnelMax = $derived(Math.max(...app.analytics.funnel.map((stage) => stage.value)));
	const donut = $derived.by(() => {
		const total = app.analytics.audience.reduce((sum, slice) => sum + slice.value, 0);
		let offset = 0;
		const r = 54;
		const c = 2 * Math.PI * r;
		return app.analytics.audience.map((slice) => {
			const length = (slice.value / total) * c;
			const dash = { dasharray: `${length} ${c - length}`, dashoffset: -offset };
			offset += length;
			return { ...slice, ...dash };
		});
	});

	const bestFormat = $derived([...app.analytics.formats].sort((a, b) => b.engagement - a.engagement)[0]);
	const reach30 = $derived(visible.slice(-4).reduce((sum, p) => sum + p.impressions, 0));
	const leads30 = $derived(visible.slice(-4).reduce((sum, p) => sum + p.leads, 0));
</script>

<svelte:head><title>Analytics · LinkedinPark</title></svelte:head>

<PageHeader
	eyebrow="Analytics"
	title="Close the loop between posting and pipeline."
	description="Weekly synthesis of what actually worked: hooks, formats, timing and the audience they moved."
>
	{#snippet actions()}
		<button class="btn btn-secondary btn-sm" onclick={() => notify('Weekly insight note generated by the Analyst agent', 'mint')}><Icon name="spark" size={13} /> Generate insight note</button>
		<button class="btn btn-primary btn-sm" onclick={() => notify('Report exported', 'blue')}><Icon name="download" size={13} /> Export report</button>
	{/snippet}
</PageHeader>

<div class="grid gap-3 sm:grid-cols-2 xl:grid-cols-4">
	<MetricCard label="Reach · 30 days" value={compact(reach30)} delta="22.4%" icon="eye" accent="mint" values={series.map((p) => p.impressions)} note="Impressions across all posts" />
	<MetricCard label="Engagement rate" value="5.4%" delta="0.8 pts" icon="heart" accent="blue" values={series.map((p) => (p.impressions / p.engagement) * 40)} note="Reactions + comments / reach" />
	<MetricCard label="Leads · 30 days" value={String(leads30)} delta="26.3%" icon="leads" accent="lime" values={series.map((p) => p.leads + 18)} note="Profile-to-lead conversions" />
	<MetricCard label="Best format" value={bestFormat.format} delta={`${bestFormat.engagement}% eng.`} icon="star" accent="amber" values={app.analytics.formats.map((f) => f.engagement)} note={`${bestFormat.leads} leads attributed`} />
</div>

<div class="mt-3 grid gap-3 xl:grid-cols-[1.5fr_1fr]">
	<section class="card overflow-hidden">
		<div class="flex flex-wrap items-center justify-between gap-2 border-b border-line px-5 py-4">
			<div>
				<div class="text-[13px] font-semibold">Reach & engagement</div>
				<div class="mt-0.5 text-[10px] text-faint">12-week view · impressions vs. engagement</div>
			</div>
			<div class="flex items-center gap-3">
				<span class="flex items-center gap-1.5 text-[9px] text-muted"><span class="h-1.5 w-1.5 rounded-full bg-mint"></span> Impressions</span>
				<span class="flex items-center gap-1.5 text-[9px] text-muted"><span class="h-1.5 w-1.5 rounded-full bg-blue"></span> Engagement</span>
			</div>
		</div>
		<div class="p-4">
			<svg viewBox={`0 0 ${w} ${h}`} class="w-full" role="img" aria-label="Reach and engagement over 12 weeks">
				<defs>
					<linearGradient id="anFill" x1="0" y1="0" x2="0" y2="1">
						<stop offset="0" stop-color="#6ee7d8" stop-opacity="0.22" />
						<stop offset="1" stop-color="#6ee7d8" stop-opacity="0" />
					</linearGradient>
				</defs>
				{#each [0.3, 0.55, 0.8] as ratio}
					<line x1="0" x2={w} y1={h * ratio} y2={h * ratio} stroke="rgba(255,255,255,0.05)" stroke-dasharray="3 5" />
				{/each}
				<path d={impArea} fill="url(#anFill)" />
				<path d={impLine} fill="none" stroke="#6ee7d8" stroke-width="2.4" stroke-linecap="round" />
				<path d={engLine} fill="none" stroke="#7aa2ff" stroke-width="1.8" stroke-linecap="round" stroke-dasharray="0" />
				{#each visible as point, i}
					{#if i % 2 === 0}
						<text x={(i / (visible.length - 1)) * w} y={h - 6} text-anchor="middle" fill="#667386" font-size="9" font-family="Inter">{point.label}</text>
					{/if}
				{/each}
			</svg>
		</div>
	</section>

	<section class="card p-5">
		<div class="flex items-center justify-between">
			<div class="text-[13px] font-semibold">Content → pipeline</div>
			<span class="chip chip-mint !py-0.5 text-[8.5px]">90 days</span>
		</div>
		<div class="mt-4 space-y-3">
			{#each app.analytics.funnel as stage, index}
				{@const width = (stage.value / funnelMax) * 100}
				<div>
					<div class="flex items-center justify-between text-[10.5px]">
						<span class="text-muted">{stage.label}</span>
						<span class="flex items-center gap-2">
							<span class="stat-number text-[12px]">{compact(stage.value)}</span>
							{#if index > 0}
								{@const prev = app.analytics.funnel[index - 1]}
								<span class="font-mono text-[8.5px] text-faint">{Math.round((stage.value / prev.value) * 100)}%</span>
							{/if}
						</span>
					</div>
					<div class="mt-1 h-2.5 overflow-hidden rounded-md bg-white/6">
						<div class="h-full rounded-md bg-gradient-to-r {['from-mint to-teal-300', 'from-blue to-indigo-400', 'from-lime to-green-300', 'from-amber to-orange-300', 'from-violet to-purple-300'][index]}" style={`width:${Math.max(6, width)}%`}></div>
					</div>
					<div class="mt-1 text-[9px] text-faint">{stage.note}</div>
				</div>
			{/each}
		</div>
		<div class="mt-4 rounded-lg border border-mint/15 bg-mint/5 p-3">
			<div class="text-[10px] text-mint">17 meetings from content this quarter · $1.24m influenced pipeline</div>
		</div>
	</section>
</div>

<div class="mt-3 grid gap-3 xl:grid-cols-3">
	<section class="card overflow-hidden">
		<div class="border-b border-line px-4 py-3.5">
			<div class="text-[12.5px] font-semibold">Format performance</div>
			<div class="mt-0.5 text-[9.5px] text-faint">Average score and engagement by format</div>
		</div>
		<div class="divide-y divide-line">
			{#each app.analytics.formats as row}
				<div class="grid grid-cols-[minmax(0,1fr)_54px_54px_54px] items-center gap-2 px-4 py-2.5">
					<div class="flex items-center gap-2">
						<span class="text-[10.5px] font-medium">{row.format}</span>
						<span class="font-mono text-[8px] text-faint">{row.posts} posts</span>
					</div>
					<span class="stat-number text-right text-[11px] text-mint">{row.avgScore}</span>
					<span class="text-right text-[9.5px] text-muted">{row.engagement}%</span>
					<span class="text-right text-[9.5px] text-faint">{row.leads} leads</span>
				</div>
			{/each}
		</div>
	</section>

	<section class="card p-4">
		<div class="text-[12.5px] font-semibold">Top hooks</div>
		<div class="mt-0.5 text-[9.5px] text-faint">Ranked by engagement rate</div>
		<div class="mt-3 space-y-2.5">
			{#each app.analytics.topHooks as hook, index}
				<div class="rounded-lg border border-line bg-panel-2/40 p-2.5">
					<div class="flex items-center justify-between">
						<span class="font-mono text-[8px] uppercase tracking-wider text-faint">#{index + 1} · {hook.format}</span>
						<span class="stat-number text-[12px] text-mint">{hook.rate}%</span>
					</div>
					<div class="mt-1 text-[10px] leading-snug text-muted">{hook.hook}</div>
				</div>
			{/each}
		</div>
	</section>

	<section class="card flex flex-col p-5">
		<div class="text-[12.5px] font-semibold">Audience mix</div>
		<div class="mt-0.5 text-[9.5px] text-faint">Engaged profiles by role family</div>
		<div class="mt-4 flex items-center justify-center">
			<div class="relative">
				<svg width="140" height="140" viewBox="0 0 140 140" role="img" aria-label="Audience mix donut">
					{#each donut as slice}
						<circle cx="70" cy="70" r="54" fill="none" stroke={slice.color} stroke-width="16" stroke-dasharray={slice.dasharray} stroke-dashoffset={slice.dashoffset} transform="rotate(-90 70 70)" />
					{/each}
					<circle cx="70" cy="70" r="38" fill="#0d121a" />
					<text x="70" y="66" text-anchor="middle" fill="#eef2f7" font-size="18" font-weight="600" font-family="Inter Tight">318</text>
					<text x="70" y="82" text-anchor="middle" fill="#667386" font-size="8" font-family="Inter">LEADS</text>
				</svg>
			</div>
		</div>
		<div class="mt-3 space-y-1.5">
			{#each app.analytics.audience as slice}
				<div class="flex items-center justify-between text-[10px]">
					<span class="flex items-center gap-1.5 text-muted"><span class="h-2 w-2 rounded-sm" style={`background:${slice.color}`}></span>{slice.label}</span>
					<span class="stat-number text-[10.5px]">{slice.value}%</span>
